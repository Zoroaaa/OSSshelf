#!/usr/bin/env node
/**
 * sync-models-dev.mjs
 * 生成 models.dev 精简快照：apps/api/src/lib/ai/catalog/modelsDevCatalog.ts
 *
 * 用法：pnpm --filter api models:sync
 * 快照随代码提交，运行时零外网依赖。
 *
 * 快照策略（2026-11-25）：
 * - 全量 provider 保留元数据（name/api/doc/npm/env/modelCount），供「新建供应商」目录选取；
 * - 仅 MODEL_DETAIL_PROVIDER_IDS 白名单保留模型明细，控制体积（全量明细约 3.6MB，
 *   白名单明细约 0.6MB），避免 D1 单行与前端 bundle 膨胀。
 * - 非白名单 provider 的模型元数据兜底：用户连接后走 /models 实时发现 + 供应商原始响应。
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

/** 仅这些 provider 保留模型明细；其余 provider 只保留元数据 + modelCount */
const MODEL_DETAIL_PROVIDER_IDS = new Set([
  'cloudflare-workers-ai',
  'deepseek',
  'openai',
  'anthropic',
  'google',
  'siliconflow',
  'siliconflow-cn',
  'moonshotai',
  'moonshotai-cn',
  'zhipuai',
  'alibaba',
  'alibaba-cn',
  'volcengine',
  'minimax',
  'xai',
  'mistral',
  'groq',
  'openrouter',
  'perplexity',
  // 新增国内原厂 / 平台
  'modelscope',
  'stepfun',
  'sensenova',
  'xiaomi',
  'qiniu-ai',
  // 新增国际原厂
  'nvidia',
  'meta',
  'cohere',
  'ai21',
  'sambanova',
  // 新增聚合平台
  'agnes',
  'opencode',
  'togetherai',
  'fireworks-ai',
  'deepinfra',
  'novita-ai',
  'huggingface',
  '302ai',
  'zenmux',
]);

const MODEL_FIELDS = [
  'attachment',
  'reasoning',
  'reasoning_options',
  'tool_call',
  'modalities',
  'limit',
  'cost',
  'status',
  'release_date',
];

function compactModel(model) {
  const out = {};
  if (typeof model.name === 'string') out.name = model.name;

  for (const field of MODEL_FIELDS) {
    const value = model[field];
    if (value === undefined || value === null) continue;

    if (field === 'reasoning_options') {
      out.reasoningOptions = value.map((option) => ({
        type: option.type,
        ...(option.values ? { values: option.values } : {}),
      }));
      continue;
    }

    if (field === 'modalities') {
      out.modalities = {
        ...(value.input ? { input: value.input } : {}),
        ...(value.output ? { output: value.output } : {}),
      };
      continue;
    }

    if (field === 'limit') {
      out.limit = {
        ...(value.context !== undefined ? { context: value.context } : {}),
        ...(value.input !== undefined ? { input: value.input } : {}),
        ...(value.output !== undefined ? { output: value.output } : {}),
      };
      continue;
    }

    if (field === 'cost') {
      out.cost = {
        ...(value.input !== undefined ? { input: value.input } : {}),
        ...(value.output !== undefined ? { output: value.output } : {}),
        ...(value.reasoning !== undefined ? { reasoning: value.reasoning } : {}),
        ...(value.cache_read !== undefined ? { cacheRead: value.cache_read } : {}),
      };
      continue;
    }

    if (field === 'tool_call') {
      out.toolCall = value;
      continue;
    }

    if (field === 'release_date') {
      out.releaseDate = value;
      continue;
    }

    out[field] = value;
  }

  return out;
}

async function main() {
  const response = await fetch('https://models.dev/api.json', {
    headers: { accept: 'application/json' },
  });

  if (!response.ok) {
    throw new Error(`models.dev responded ${response.status}`);
  }

  const source = await response.json();
  const providers = {};

  // 全量 provider 都写入元数据（供新建供应商目录选取）；模型明细仅白名单保留。
  for (const providerId of Object.keys(source).sort()) {
    const provider = source[providerId];
    if (!provider || typeof provider !== 'object') continue;

    const rawModels = provider.models && typeof provider.models === 'object' ? provider.models : {};
    const modelCount = Object.keys(rawModels).length;
    const keepDetails = MODEL_DETAIL_PROVIDER_IDS.has(providerId);
    const models = {};
    if (keepDetails) {
      for (const modelId of Object.keys(rawModels).sort()) {
        models[modelId] = compactModel(rawModels[modelId]);
      }
    }

    providers[providerId] = {
      name: String(provider.name ?? providerId),
      ...(provider.api ? { api: provider.api } : {}),
      ...(provider.doc ? { doc: provider.doc } : {}),
      ...(provider.npm ? { npm: provider.npm } : {}),
      ...(provider.env ? { env: provider.env } : {}),
      modelCount,
      models,
    };
  }

  const snapshot = {
    generatedAt: new Date().toISOString(),
    providers,
  };

  const scriptDir = dirname(fileURLToPath(import.meta.url));
  const target = join(scriptDir, '..', 'src', 'lib', 'ai', 'catalog', 'modelsDevCatalog.ts');

  const header = [
    '/**',
    ' * modelsDevCatalog.ts',
    ' * AUTO-GENERATED by scripts/sync-models-dev.mjs — DO NOT EDIT.',
    ' * 运行 pnpm --filter api models:sync 更新。',
    ' */',
    '',
    "import type { ModelsDevSnapshot } from './types';",
    '',
    'export const MODELS_DEV_SNAPSHOT: ModelsDevSnapshot = ',
  ].join('\n');

  await writeFile(target, `${header}${JSON.stringify(snapshot)}\n`, 'utf8');

  const detailCount = Object.values(providers).reduce(
    (sum, provider) => sum + Object.keys(provider.models).length,
    0
  );
  const catalogModelCount = Object.values(providers).reduce((sum, provider) => sum + provider.modelCount, 0);
  console.log(
    `[models:sync] 写入 ${Object.keys(providers).length} 个 provider；${detailCount} 个模型明细、${catalogModelCount} 个模型总数`
  );
  console.log(`[models:sync] ${target}`);
}

main().catch((error) => {
  console.error('[models:sync] 失败:', error);
  process.exitCode = 1;
});
