#!/usr/bin/env node
/**
 * sync-models-dev.mjs
 * 生成 models.dev 精简快照：apps/api/src/lib/ai/catalog/modelsDevCatalog.ts
 *
 * 用法：pnpm --filter api models:sync
 * 快照随代码提交，运行时零外网依赖。
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const PROVIDER_IDS = [
  'cloudflare-workers-ai',
  'deepseek',
  'openai',
  'anthropic',
  'google',
  'siliconflow',
  'siliconflow-cn',
  'moonshotai',
  'moonshotai-cn',
  'zhipuai',
  'alibaba',
  'alibaba-cn',
  'volcengine',
  'minimax',
  'xai',
  'mistral',
  'groq',
  'openrouter',
  'perplexity',
];

const MODEL_FIELDS = [
  'attachment',
  'reasoning',
  'reasoning_options',
  'tool_call',
  'modalities',
  'limit',
  'cost',
  'status',
  'release_date',
];

function compactModel(model) {
  const out = {};
  if (typeof model.name === 'string') out.name = model.name;

  for (const field of MODEL_FIELDS) {
    const value = model[field];
    if (value === undefined || value === null) continue;

    if (field === 'reasoning_options') {
      out.reasoningOptions = value.map((option) => ({
        type: option.type,
        ...(option.values ? { values: option.values } : {}),
      }));
      continue;
    }

    if (field === 'modalities') {
      out.modalities = {
        ...(value.input ? { input: value.input } : {}),
        ...(value.output ? { output: value.output } : {}),
      };
      continue;
    }

    if (field === 'limit') {
      out.limit = {
        ...(value.context !== undefined ? { context: value.context } : {}),
        ...(value.input !== undefined ? { input: value.input } : {}),
        ...(value.output !== undefined ? { output: value.output } : {}),
      };
      continue;
    }

    if (field === 'cost') {
      out.cost = {
        ...(value.input !== undefined ? { input: value.input } : {}),
        ...(value.output !== undefined ? { output: value.output } : {}),
        ...(value.reasoning !== undefined ? { reasoning: value.reasoning } : {}),
        ...(value.cache_read !== undefined ? { cacheRead: value.cache_read } : {}),
      };
      continue;
    }

    if (field === 'tool_call') {
      out.toolCall = value;
      continue;
    }

    if (field === 'release_date') {
      out.releaseDate = value;
      continue;
    }

    out[field] = value;
  }

  return out;
}

async function main() {
  const response = await fetch('https://models.dev/api.json', {
    headers: { accept: 'application/json' },
  });

  if (!response.ok) {
    throw new Error(`models.dev responded ${response.status}`);
  }

  const source = await response.json();
  const providers = {};

  for (const providerId of PROVIDER_IDS) {
    const provider = source[providerId];
    if (!provider) {
      console.warn(`[models:sync] 跳过不存在的 provider: ${providerId}`);
      continue;
    }

    const models = {};
    for (const modelId of Object.keys(provider.models ?? {}).sort()) {
      models[modelId] = compactModel(provider.models[modelId]);
    }

    providers[providerId] = {
      name: provider.name,
      ...(provider.api ? { api: provider.api } : {}),
      ...(provider.doc ? { doc: provider.doc } : {}),
      ...(provider.npm ? { npm: provider.npm } : {}),
      ...(provider.env ? { env: provider.env } : {}),
      models,
    };
  }

  const snapshot = {
    generatedAt: new Date().toISOString(),
    providers,
  };

  const scriptDir = dirname(fileURLToPath(import.meta.url));
  const target = join(scriptDir, '..', 'src', 'lib', 'ai', 'catalog', 'modelsDevCatalog.ts');

  const header = [
    '/**',
    ' * modelsDevCatalog.ts',
    ' * AUTO-GENERATED by scripts/sync-models-dev.mjs — DO NOT EDIT.',
    ' * 运行 pnpm --filter api models:sync 更新。',
    ' */',
    '',
    '/* eslint-disable prettier/prettier */',
    '',
    "import type { ModelsDevSnapshot } from './types';",
    '',
    'export const MODELS_DEV_SNAPSHOT: ModelsDevSnapshot = ',
  ].join('\n');

  await writeFile(target, `${header}${JSON.stringify(snapshot)}\n`, 'utf8');

  const modelCount = Object.values(providers).reduce(
    (sum, provider) => sum + Object.keys(provider.models).length,
    0
  );
  console.log(`[models:sync] 写入 ${Object.keys(providers).length} 个 provider、${modelCount} 个模型`);
  console.log(`[models:sync] ${target}`);
}

main().catch((error) => {
  console.error('[models:sync] 失败:', error);
  process.exitCode = 1;
});
